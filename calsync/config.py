"""Config: /etc/calsync/config.toml (path can be overridden with CALSYNC_CONFIG)."""
import os
import tomllib
from dataclasses import dataclass, field

DEFAULT_PATH = "/etc/calsync/config.toml"
REMINDER_MODES = ("outlook", "none", "default")
MODES = ("one-way", "two-way")


class ConfigError(Exception):
    pass


@dataclass
class Mapping:
    source: str            # Outlook calendar name (as listed by calsync calendars)
    target: str            # Google calendar ID (new: …@group.calendar.google.com; main: Gmail address)
    name: str = ""         # for logs / --only; defaults to "source → target"
    prefix: str = ""       # title prefix, used to tell sources apart when merging into the main calendar
    reminders: str = "outlook"  # outlook = copy Outlook's; none = no reminders; default = Google's defaults
    mode: str = "one-way"       # two-way: Outlook ↔ dedicated Google calendar (target is for this mapping only)


@dataclass
class Mirror:
    name: str                  # also the name of that calendar in Outlook (created by calsync)
    icloud: str = ""           # iCloud calendar name (CalDAV)
    url_file: str = ""         # or: file with the subscription link (webcal/https); a link is a password, not kept in config
    outlook: bool = True
    outlook_name: str = ""     # its name in Outlook (default = name; set it if it clashes with an existing calendar)
    google: list = field(default_factory=list)   # Google target calendar IDs (dedicated or main calendar)


@dataclass
class Config:
    outlook_client_id: str
    google_key_file: str
    mappings: list
    past_days: int = 30
    future_days: int = 365
    outlook_timezone: str = "China Standard Time"   # timezone for times returned by Graph (Windows name)
    timezone: str = "Asia/Shanghai"                 # IANA name of the same timezone, used when writing to Google
    guard_ratio: float = 0.5   # deleting > existing × guard_ratio and > guard_min in one mapping: skip, alert
    guard_min: int = 10
    notify_url: str = ""          # alert endpoint ([notify] url); empty = alerts off
    notify_key_file: str = ""
    mirrors: list = field(default_factory=list)
    icloud_apple_id: str = ""
    icloud_password_file: str = ""
    state_dir: str = "/var/lib/calsync"
    # config page ([managed]): the page manages the B merge, [[mirror]] and subscription links; the generated
    # managed.toml lives in state_dir/managed/
    managed_url: str = ""
    managed_key_file: str = ""
    b_target: str = ""          # account B's main calendar (Gmail address)
    a_account: str = ""         # account A (used in the generated calendar-creation instructions)
    managed_active: bool = False   # managed.toml was read (B one-way / [[mirror]] in config.toml are replaced)
    token_file: str = ""       # Outlook token; default state_dir/ms_token.json (tests share it: the token rotates, no copies)
    path: str = field(default="", repr=False)


def read_raw(path):
    try:
        with open(path, "rb") as f:
            return tomllib.load(f)
    except FileNotFoundError:
        raise ConfigError(f"config not found: {path}")
    except tomllib.TOMLDecodeError as e:
        raise ConfigError(f"config parse error in {path}: {e}")


def managed_dir(raw):
    return os.path.join(raw.get("state_dir", "/var/lib/calsync"), "managed")


def merge_managed(raw, man):
    """The managed.toml generated by the config page replaces the "one-way into B main calendar" mappings and all
    [[mirror]] in config.toml (the page wins).
    Everything else (credentials, A's two-way [[sync]]) stays hand-written in config.toml."""
    b = raw["managed"]["b_target"]
    keep = [s for s in raw.get("sync", []) if not (s.get("mode", "one-way") == "one-way" and s.get("target") == b)]
    out = dict(raw)
    out["sync"] = keep + list(man.get("sync", []))
    out["mirror"] = list(man.get("mirror", []))
    return out


def load(path=None):
    path = path or os.environ.get("CALSYNC_CONFIG") or DEFAULT_PATH
    raw = read_raw(path)
    active = False
    if raw.get("managed"):
        mf = os.path.join(managed_dir(raw), "managed.toml")
        if os.path.exists(mf):
            raw = merge_managed(raw, read_raw(mf))
            active = True
    cfg = parse(raw, path)
    cfg.managed_active = active
    return cfg


def load_with_managed(path, text):
    """Build a config from managed.toml content not yet written to disk (for dry-run / checking before it takes
    effect)."""
    raw = read_raw(path)
    try:
        man = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise ConfigError(f"generated managed config does not parse: {e}")
    cfg = parse(merge_managed(raw, man), path)
    cfg.managed_active = True
    return cfg


def parse(raw, path=""):
    outlook = raw.get("outlook", {})
    google = raw.get("google", {})
    notify = raw.get("notify", {})
    if not outlook.get("client_id"):
        raise ConfigError("[outlook] client_id is required")
    if not google.get("key_file"):
        raise ConfigError("[google] key_file is required")

    mappings = []
    for i, m in enumerate(raw.get("sync", []), 1):
        if not m.get("source") or not m.get("target"):
            raise ConfigError(f"[[sync]] #{i}: source and target are required")
        rem = m.get("reminders", "outlook")
        if rem not in REMINDER_MODES:
            raise ConfigError(f"[[sync]] #{i}: reminders must be one of {REMINDER_MODES}")
        mode = m.get("mode", "one-way")
        if mode not in MODES:
            raise ConfigError(f"[[sync]] #{i}: mode must be one of {MODES}")
        if mode == "two-way" and m.get("prefix"):
            raise ConfigError(f"[[sync]] #{i}: two-way mappings cannot have a prefix (it would be written back to Outlook)")
        mappings.append(Mapping(
            source=m["source"], target=m["target"],
            name=m.get("name") or f"{m['source']} → {m['target']}",
            prefix=m.get("prefix", ""), reminders=rem, mode=mode,
        ))
    mirrors = []
    for i, m in enumerate(raw.get("mirror", []), 1):
        if not m.get("name"):
            raise ConfigError(f"[[mirror]] #{i}: name is required")
        if bool(m.get("icloud")) == bool(m.get("url_file")):
            raise ConfigError(f"[[mirror]] {m['name']}: exactly one of icloud / url_file is required")
        mir = Mirror(name=m["name"], icloud=m.get("icloud", ""), url_file=m.get("url_file", ""),
                     outlook=bool(m.get("outlook", True)), outlook_name=m.get("outlook_name", ""),
                     google=list(m.get("google", [])))
        if any(x.source == (mir.outlook_name or mir.name) for x in mappings) and mir.outlook:
            raise ConfigError(f"[[mirror]] {mir.name}: its Outlook calendar would also be a [[sync]] source (loop)")
        if any(x.mode == "two-way" and x.target in mir.google for x in mappings):
            raise ConfigError(f"[[mirror]] {mir.name}: a two-way target cannot also be a mirror target")
        mirrors.append(mir)
    if not mappings and not mirrors:
        raise ConfigError("no [[sync]] or [[mirror]] entries")
    names = [m.name for m in mappings]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        raise ConfigError(f"duplicate [[sync]] names: {sorted(dup)}")
    for m in mappings:
        if m.mode == "two-way" and sum(x.target == m.target for x in mappings) > 1:
            raise ConfigError(f"{m.name}: a two-way target must be a dedicated calendar used by no other [[sync]]")
    pairs = [(m.source, m.target) for m in mappings]
    if len(set(pairs)) != len(pairs):
        raise ConfigError("the same source → target pair appears twice")

    cfg = Config(
        outlook_client_id=outlook["client_id"],
        google_key_file=google["key_file"],
        mappings=mappings,
        mirrors=mirrors,
        icloud_apple_id=raw.get("icloud", {}).get("apple_id", ""),
        icloud_password_file=raw.get("icloud", {}).get("password_file", ""),
        notify_key_file=notify.get("key_file", ""),
        path=path,
    )
    for key in ("past_days", "future_days", "outlook_timezone", "timezone",
                "guard_ratio", "guard_min", "state_dir", "token_file"):
        if key in raw:
            setattr(cfg, key, raw[key])
    if "url" in notify:
        cfg.notify_url = notify["url"]
    man = raw.get("managed")
    if man:
        if not str(man.get("url", "")).startswith("https://") or not man.get("key_file") or not man.get("b_target"):
            raise ConfigError("[managed] needs url (https://…), key_file and b_target")
        cfg.managed_url = man["url"].rstrip("/")
        cfg.managed_key_file = man["key_file"]
        cfg.b_target = man["b_target"]
        cfg.a_account = man.get("a_account", "")
    return cfg
