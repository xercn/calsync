"""Config page (calsync.example.com). The page manages three things: which iCloud / subscribed
calendars are copied ([[mirror]]), which Outlook calendars are merged one-way into the B main calendar
([[sync]] → b_target), and subscription links. Everything else (credentials, A's two-way sync) stays hand-written
in config.toml.

The server connects to the Worker on its own (no open port), with the key /etc/calsync/manage.key:
- poll: once a minute (calsync-poll.timer), and also at the start of every scheduled sync;
- draft → dry-run against the draft (per target: counts of + ~ -) and send the result back;
- The user confirms → dry-run again with the new settings; managed.toml is written only if each deletion count is at
  most the page dry-run + 10 (sync.CAP_SLACK), otherwise nothing is touched and a failure is reported;
- calendars removed from the settings: events already synced are not deleted, they are recorded as "leftover
  events" and only deleted when "Clean up" is clicked on the page (same +10 cap);
- Worker unreachable: keep using the last effective managed.toml and clear nothing; 24 hours of continuous failure
  raises an alert.

Files (state_dir/managed/, calsync 700): managed.toml (generated [[sync]] / [[mirror]]), managed.json (revision,
content, leftover events), subs/<id>.url (subscription link, 600), poll.json, last_run.json.
"""
import json
import os
import re
import shutil
import time

import requests

from . import config, render
from .http import UA
from .state import State

STALE = 24 * 3600
INTERVALS = (5, 10, 15, 30)      # sync interval (minutes), chosen on the page
DEFAULT_INTERVAL = 10
SLACK = 45                       # checked every minute; due 45 s early so 10 min does not become 11
SUB_ID = re.compile(r"^[0-9a-f]{16}$")


class ApiError(Exception):
    pass


class ApplyError(Exception):
    pass


# ---------------------------------------------------------------- files

def mdir(cfg):
    d = os.path.join(cfg.state_dir, "managed")
    os.makedirs(d, mode=0o700, exist_ok=True)
    return d


def _read(path, default):
    try:
        with open(path) as f:
            return json.load(f)
    except (FileNotFoundError, ValueError):
        return default


def _write(path, data, mode=0o600):
    tmp = path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w") as f:
        f.write(data if isinstance(data, str) else json.dumps(data, ensure_ascii=False))
    os.replace(tmp, path)


def local(cfg):
    return _read(os.path.join(mdir(cfg), "managed.json"), {"rev": 0, "body": None, "leftovers": []})


def save_local(cfg, loc):
    _write(os.path.join(mdir(cfg), "managed.json"), loc)


def _version():
    try:
        with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "VERSION")) as f:
            return f.read().strip()
    except OSError:
        return "dev"


# ---------------------------------------------------------------- settings content ↔ config

def refs(body):
    return [m["sub"] for m in body.get("mirrors", []) if m.get("sub")]


def names(body):
    """The mapping names this settings body manages (used by --only)."""
    return ["B-" + n for n in body.get("b_merge", [])] + [m["name"] for m in body.get("mirrors", [])]


def pairs(body, b_target):
    """{(kind, name, target)}: every "source → target" pair."""
    out = {("sync", "B-" + n, b_target) for n in body.get("b_merge", [])}
    for m in body.get("mirrors", []):
        if m.get("outlook", True):
            out.add(("mirror", m["name"], "outlook"))
        if m.get("a"):
            out.add(("mirror", m["name"], m["a"]))
        if m.get("b"):
            out.add(("mirror", m["name"], b_target))
    return out


def normalize(body):
    """For comparison (when importing, check whether the page and config.toml hold the same settings)."""
    return {
        "b_merge": sorted(set(body.get("b_merge", []))),
        "mirrors": sorted(({"name": m["name"], "icloud": m.get("icloud", ""), "sub": m.get("sub", ""),
                            "outlook": m.get("outlook", True) is not False,
                            "outlook_name": (m.get("outlook_name") or "") if m.get("outlook", True) is not False else "",
                            "a": m.get("a") or "", "b": bool(m.get("b"))}
                           for m in body.get("mirrors", [])), key=lambda m: m["name"]),
    }


def _q(s):
    return json.dumps(s, ensure_ascii=False)   # a JSON string is also a valid TOML basic string


def to_toml(body, b_target, subs_dir, rev=0):
    out = [f"# Generated by the config page (revision #{rev}). Do not edit: the next confirmed change overwrites it.", ""]
    for n in body.get("b_merge", []):
        out += ["[[sync]]", f"name = {_q('B-' + n)}", f"source = {_q(n)}", f"target = {_q(b_target)}", ""]
    for m in body.get("mirrors", []):
        out += ["[[mirror]]", f"name = {_q(m['name'])}"]
        if m.get("sub"):
            if not SUB_ID.match(m["sub"]):
                raise ApplyError(f"{m['name']}: bad subscription id")
            out.append(f"url_file = {_q(os.path.join(subs_dir, m['sub'] + '.url'))}")
        else:
            out.append(f"icloud = {_q(m['icloud'])}")
        outlook = m.get("outlook", True) is not False
        out.append(f"outlook = {'true' if outlook else 'false'}")
        if outlook and m.get("outlook_name"):
            out.append(f"outlook_name = {_q(m['outlook_name'])}")
        google = ([m["a"]] if m.get("a") else []) + ([b_target] if m.get("b") else [])
        out += [f"google = [{', '.join(_q(g) for g in google)}]", ""]
    return "\n".join(out)


def current_body(cfg):
    """The currently effective config → the page's settings format (for the first import, and for working out "stop
    syncing" in the dry-run).
    Raises ValueError for anything it cannot express."""
    b = cfg.b_target
    bm = []
    for m in cfg.mappings:
        if m.mode == "one-way" and m.target == b:
            if m.name != "B-" + m.source or m.prefix or m.reminders != "outlook":
                raise ValueError(f"[[sync]] {m.name}: only plain 'B-<source>' entries can be managed by the page")
            bm.append(m.source)
    subs_dir = os.path.join(cfg.state_dir, "managed", "subs")
    mirrors = []
    for x in cfg.mirrors:
        e = {"name": x.name, "outlook": x.outlook, "outlook_name": x.outlook_name}
        if x.url_file:
            sid = os.path.basename(x.url_file)[:-4]
            if os.path.dirname(x.url_file) != subs_dir or not x.url_file.endswith(".url") or not SUB_ID.match(sid):
                raise ValueError(f"[[mirror]] {x.name}: subscription links must be added on the page")
            e["sub"] = sid
        else:
            e["icloud"] = x.icloud
        a = [g for g in x.google if g != b]
        if len(a) > 1:
            raise ValueError(f"[[mirror]] {x.name}: more than one non-B Google target")
        e["a"] = a[0] if a else ""
        e["b"] = b in x.google
        mirrors.append(e)
    return {"b_merge": bm, "mirrors": mirrors}


def _write_subs(d, urls):
    os.makedirs(d, mode=0o700, exist_ok=True)
    for sid, url in urls.items():
        if not SUB_ID.match(sid):
            raise ApplyError("bad subscription id")
        _write(os.path.join(d, sid + ".url"), url.strip() + "\n")


def _prune_subs(d, keep):
    if not os.path.isdir(d):
        return
    for fn in os.listdir(d):
        if fn.endswith(".url") and fn[:-4] not in keep:
            os.remove(os.path.join(d, fn))


# ---------------------------------------------------------------- Worker

class Api:
    def __init__(self, cfg):
        self.url = cfg.managed_url
        try:
            with open(cfg.managed_key_file) as f:
                self.key = f.read().strip()
        except OSError as e:
            raise ApiError(f"key file: {e.__class__.__name__}")

    def _req(self, method, path, body=None):
        try:
            r = requests.request(method, self.url + path, json=body, timeout=30,
                                 headers={"Authorization": f"Bearer {self.key}", "User-Agent": UA})
        except requests.RequestException as e:
            raise ApiError(e.__class__.__name__)
        if r.status_code != 200:
            raise ApiError(f"HTTP {r.status_code} {path}: {r.text[:200]}")
        try:
            return r.json()
        except ValueError:
            raise ApiError(f"non-JSON reply from {path}")

    def poll(self):
        return self._req("GET", "/agent/poll")

    def post(self, path, body):
        return self._req("POST", path, body)


def _post(api, path, body, log):
    try:
        api.post(path, body)
        return True
    except ApiError as e:
        log(f"config page: {path} failed: {e}")
        return False


def poll_ok(cfg):
    _write(os.path.join(mdir(cfg), "poll.json"), {"last_ok": time.time()}, 0o644)


def poll_failed(cfg, err, log=print):
    log(f"config page unreachable: {err}")


def stale_error(cfg, now=None):
    """Unable to reach the config page for 24 hours in a row → one error (goes to alerts); otherwise None."""
    now = now or time.time()
    path = os.path.join(mdir(cfg), "poll.json")
    st = _read(path, None)
    if not st:                      # first time: start counting from now
        poll_ok(cfg)
        return None
    hours = (now - st.get("last_ok", now)) / 3600
    if hours * 3600 >= STALE:
        return f"config page unreachable for {hours:.0f} h; keeping the last applied settings"
    return None


def has_work(cfg, p):
    return bool(p.get("confirmed") or p.get("draft") or p.get("cleanups") or p.get("want_inventory"))


# ---------------------------------------------------------------- scheduling (calsync-poll.timer fires once a minute
# and is the only timer)

def _sched_path(cfg):
    return os.path.join(mdir(cfg), "schedule.json")


def interval(cfg, p=None):
    """The interval (minutes) set on the page; if the page is unreachable, the last recorded one, or 10 if none."""
    st = _read(_sched_path(cfg), {})
    if p and p.get("interval") in INTERVALS:
        if st.get("interval") != p["interval"]:
            st["interval"] = p["interval"]
            _write(_sched_path(cfg), st, 0o644)
        return p["interval"]
    return st.get("interval") if st.get("interval") in INTERVALS else DEFAULT_INTERVAL


def due(cfg, minutes, now=None):
    now = now or time.time()
    last = _read(_sched_path(cfg), {}).get("last_run")
    return last is None or now - last >= minutes * 60 - SLACK


def record_run(cfg, now=None):
    """A full sync round (success or failure) has finished: the next round counts from now."""
    st = _read(_sched_path(cfg), {})
    st["last_run"] = now or time.time()
    _write(_sched_path(cfg), st, 0o644)


def ack_sync(cfg, at, log=print):
    try:
        _post(Api(cfg), "/agent/ack-sync", {"at": at}, log)
    except ApiError as e:
        log(f"config page: {e}")


# ---------------------------------------------------------------- one round

def cycle(cfg, ctx, poll=None, log=print):
    """→ (cfg, errors). When new settings have just taken effect, returns the new cfg (the caller syncs one round with
    it right away)."""
    errors = []
    try:
        api = Api(cfg)
        if poll is None:
            poll = api.poll()
            poll_ok(cfg)
    except ApiError as e:
        poll_failed(cfg, e, log)
        err = stale_error(cfg)
        return cfg, [err] if err else []

    loc = local(cfg)
    for c in poll.get("cleanups") or []:
        cleanup(cfg, ctx, api, loc, c, log)

    new_cfg = cfg
    conf = poll.get("confirmed")
    page_applied = poll.get("applied")
    if conf:
        if conf["id"] == loc.get("rev"):          # already effective, the last report was not delivered
            _post(api, "/agent/applied", {"rev": conf["id"], "ok": True}, log)
        else:
            new_cfg = apply(cfg, ctx, api, loc, conf, poll.get("subs") or {}, log) or cfg
    elif page_applied and page_applied["id"] != loc.get("rev"):
        errors.append(f"config page shows version #{page_applied['id']} in effect but this machine has "
                      f"#{loc.get('rev')}; check {mdir(cfg)}")

    if poll.get("draft"):
        preview(new_cfg, ctx, api, local(new_cfg), poll["draft"], poll.get("subs") or {}, log)
    if (poll.get("want_inventory") or poll.get("cleanups")) and new_cfg is cfg:   # after a cleanup, show the page now
        upload_inventory(cfg, ctx, log, api=api)
    return new_cfg, errors


def _applied_body(cfg, loc):
    if loc.get("rev"):
        return loc["body"]
    try:
        return current_body(cfg)
    except ValueError:
        return {"b_merge": [], "mirrors": []}


def preview(cfg, ctx, api, loc, draft, subs, log):
    from .cli import sync_all
    rev, body = draft["id"], draft["body"]
    tmp = os.path.join(mdir(cfg), "preview-subs")
    shutil.rmtree(tmp, ignore_errors=True)
    rows, errors = [], []
    try:
        missing = [s for s in refs(body) if s not in subs]
        if missing:
            raise ApplyError("subscription link not found on the page")
        _write_subs(tmp, {s: subs[s] for s in refs(body)})
        dcfg = config.load_with_managed(cfg.path, to_toml(body, cfg.b_target, tmp, rev))
        old = _applied_body(cfg, loc)
        for m in body.get("mirrors", []):
            o = next((x for x in old.get("mirrors", []) if x["name"] == m["name"]), None)
            if o and o.get("outlook", True) and m.get("outlook", True) and (o.get("outlook_name") or "") != (m.get("outlook_name") or ""):
                errors.append(f"{m['name']}: renaming its Outlook calendar is not supported; remove it and add it again")
        errs, rows = sync_all(dcfg, ctx, dry_run=True, only=names(body))
        rows = [r for r in rows if r["kind"] != "two-way"]
        old_p, new_p = pairs(old, cfg.b_target), pairs(body, cfg.b_target)
        for r in rows:
            r["state"] = "same" if (r["kind"], r["name"], r["target"]) in old_p else "new"
        attached = [r["error"] for r in rows if r.get("error")]
        errors += [e for e in errs if not any(a in e for a in attached)]
        for kind, name, target in sorted(old_p - new_p):
            rows.append({"kind": kind, "name": name, "target": target, "state": "stop",
                         "existing": _count(cfg, ctx, _leftover(cfg, ctx, kind, name, target, old))})
    except (ApplyError, config.ConfigError, OSError) as e:
        errors.append(f"{e.__class__.__name__}: {e}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    log(f"config page: preview of version #{rev}: {len(rows)} rows, {len(errors) + sum(1 for r in rows if r.get('error'))} errors")
    _post(api, "/agent/preview", {"rev": rev, "rows": rows, "errors": errors}, log)


def apply(cfg, ctx, api, loc, conf, subs, log):
    """Make the confirmed settings effective. On success returns the new cfg; on failure reports to the page, touches
    nothing and returns None."""
    from .cli import sync_all
    rev, body = conf["id"], conf["body"]
    subs_dir = os.path.join(mdir(cfg), "subs")
    keep = set(refs(_applied_body(cfg, loc)))
    try:
        if conf.get("seed"):
            if normalize(body) != normalize(current_body(cfg)):
                raise ApplyError("imported settings differ from config.toml")
        missing = [s for s in refs(body) if s not in subs]
        if missing:
            raise ApplyError("subscription link not found on the page")
        _write_subs(subs_dir, {s: subs[s] for s in refs(body)})
        text = to_toml(body, cfg.b_target, subs_dir, rev)
        new_cfg = config.load_with_managed(cfg.path, text)
        if not conf.get("seed"):
            caps = {(r["kind"], r["name"], r["target"]): int(r.get("delete") or 0)
                    for r in (conf.get("preview") or {}).get("rows", []) if r.get("state") != "stop"}
            errs, _ = sync_all(new_cfg, ctx, dry_run=True, only=names(body), caps=caps)
            if errs:
                raise ApplyError(*errs)
        old = _applied_body(cfg, loc)
        leftovers = _update_leftovers(cfg, ctx, old, body, loc.get("leftovers") or [])
        _write(os.path.join(mdir(cfg), "managed.toml"), text, 0o644)
        save_local(cfg, {"rev": rev, "body": body, "leftovers": leftovers, "applied_at": time.time()})
        _prune_subs(subs_dir, set(refs(body)))
    except (ApplyError, config.ConfigError, ValueError, OSError) as e:
        _prune_subs(subs_dir, keep)
        errs = list(e.args) if isinstance(e, ApplyError) else [f"{e.__class__.__name__}: {e}"]
        log(f"config page: version #{rev} NOT applied: {errs[0]}")
        _post(api, "/agent/applied", {"rev": rev, "ok": False, "errors": [str(x)[:300] for x in errs[:20]]}, log)
        return None
    log(f"config page: version #{rev} applied")
    _post(api, "/agent/applied", {"rev": rev, "ok": True}, log)
    return config.load(cfg.path)


# ---------------------------------------------------------------- leftover events / cleanup

def _leftover(cfg, ctx, kind, name, target, body):
    """→ {kind, name, target, mid, calendar}; mid is None when it cannot be found."""
    e = {"kind": kind, "name": name, "target": target, "mid": None, "calendar": ""}
    if kind == "sync":
        cal = [c for c in ctx.cals if c["name"] == name[2:]]
        if len(cal) == 1:
            e["mid"] = render.map_id(cal[0]["id"], target)
    else:
        e["mid"] = render.map_id(f"mirror:{name}", target)
        if target == "outlook":
            m = next((x for x in body.get("mirrors", []) if x["name"] == name), {})
            e["calendar"] = m.get("outlook_name") or name
    return e


def _count(cfg, ctx, lo):
    """Number of leftover events; None if that Outlook calendar no longer exists."""
    if not lo.get("mid"):
        return None
    if lo["target"] == "outlook":
        o_cal = State(os.path.join(cfg.state_dir, "state.db")).mirror_cal(lo["mid"])
        if not o_cal or not any(c["id"] == o_cal for c in ctx.cals):
            return None
        from . import sync
        _, wide = sync.windows(cfg)
        return len(ctx.graph.calendar_view(o_cal, wide[0], wide[1], cfg.outlook_timezone))
    return len(ctx.gcal.list_marked(lo["target"], map_id=lo["mid"]))


def _update_leftovers(cfg, ctx, old, new, leftovers):
    new_p = pairs(new, cfg.b_target)
    out = [lo for lo in leftovers if (lo["kind"], lo["name"], lo["target"]) not in new_p]
    have = {(lo["kind"], lo["name"], lo["target"]) for lo in out}
    for k in sorted(pairs(old, cfg.b_target) - new_p):
        if k not in have:
            out.append(_leftover(cfg, ctx, *k, old))
    return out


def cleanup(cfg, ctx, api, loc, c, log):
    key = (c["kind"], c["name"], c["target"])
    lo = next((x for x in loc.get("leftovers") or [] if (x["kind"], x["name"], x["target"]) == key), None)
    res = {"id": c["id"], "ok": False, "deleted": 0}
    try:
        if lo is None:
            raise ApplyError("not in the leftover list (re-added, or already cleaned)")
        if loc.get("body") and key in pairs(loc["body"], cfg.b_target):
            raise ApplyError("this calendar is being synced again; nothing deleted")
        if not lo.get("mid"):
            raise ApplyError("cannot identify the events (source calendar gone); clean up by hand")
        limit = int(c.get("count") or 0) + 10
        if lo["target"] == "outlook":
            st = State(os.path.join(cfg.state_dir, "state.db"))
            o_cal = st.mirror_cal(lo["mid"])
            n = _count(cfg, ctx, lo)
            if n is not None:
                if n > limit:
                    raise ApplyError(f"Outlook calendar now has {n} events, page showed {c.get('count')}; nothing deleted")
                ctx.graph.delete_calendar(o_cal)
                res["deleted"] = n
            st.drop_mirror_cal(lo["mid"])
        else:
            marked = ctx.gcal.list_marked(lo["target"], map_id=lo["mid"])
            if len(marked) > limit:
                raise ApplyError(f"{len(marked)} events now, page showed {c.get('count')}; nothing deleted")
            for gid in marked:
                ctx.gcal.delete(lo["target"], gid)
                res["deleted"] += 1
        loc["leftovers"] = [x for x in loc["leftovers"] if x is not lo]
        save_local(cfg, loc)
        res["ok"] = True
        log(f"config page: cleaned up {c['name']} → {c['target']}: {res['deleted']} deleted")
    except Exception as e:
        res["error"] = f"{e.__class__.__name__}: {str(e)[:200]}"
        log(f"config page: cleanup {c['name']} → {c['target']} failed: {res['error']}")
    _post(api, "/agent/cleanup", res, log)


# ---------------------------------------------------------------- inventory

def after_run(cfg, ctx, errors, rows, log=print):
    last = {"at": int(time.time()), "ok": not errors, "errors": [e[:300] for e in errors[:20]], "rows": rows}
    _write(os.path.join(mdir(cfg), "last_run.json"), last, 0o644)
    upload_inventory(cfg, ctx, log, last_run=last)


def upload_inventory(cfg, ctx, log=print, api=None, last_run=None):
    try:
        api = api or Api(cfg)
    except ApiError as e:
        log(f"config page: {e}")
        return
    loc = local(cfg)
    mine = State(os.path.join(cfg.state_dir, "state.db")).mirror_cals()
    inv = {
        "at": int(time.time()), "version": _version(), "b_target": cfg.b_target, "a_account": cfg.a_account,
        "sa_email": getattr(ctx.gcal, "email", ""), "timezone": cfg.timezone, "managed_rev": loc.get("rev"),
        "outlook": [{"name": c["name"], "canEdit": bool(c.get("canEdit")), "calsync": c["id"] in mine} for c in ctx.cals],
        "two_way": [{"name": m.name, "source": m.source, "target": m.target} for m in cfg.mappings if m.mode == "two-way"],
        "last_run": last_run or _read(os.path.join(mdir(cfg), "last_run.json"), None),
    }
    try:
        ic = ctx.icloud()
        inv["icloud"] = sorted(c["name"] for c in ic.calendars()) if ic else []
    except Exception as e:
        inv["icloud"], inv["icloud_error"] = [], f"{e.__class__.__name__}"
    try:
        inv["current"] = current_body(cfg)
    except ValueError as e:
        inv["current"], inv["current_error"] = None, str(e)
    left, keep = [], []
    for lo in loc.get("leftovers") or []:
        try:
            n = _count(cfg, ctx, lo)
        except Exception:
            n = -1
        if n is None or (n == 0 and lo["target"] != "outlook"):
            continue                  # nothing left to clean
        keep.append(lo)
        left.append({k: lo[k] for k in ("kind", "name", "target", "calendar")} | {"count": n})
    if len(keep) != len(loc.get("leftovers") or []):
        loc["leftovers"] = keep
        save_local(cfg, loc)
    inv["leftovers"] = left
    _post(api, "/agent/inventory", inv, log)
